android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.scan.xyzabc"
    minSdk = 24
    targetSdk = 36
    // A fixed version code cannot be updated: the store refuses an APK whose
    // code is not higher than the one already published. The build number of
    // the CI run is what makes every release installable over the last.
    versionCode = (System.getenv("VERSION_CODE") ?: "1").toIntOrNull() ?: 1
    versionName = System.getenv("VERSION_NAME") ?: "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = System.getenv("KEY_ALIAS") ?: "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
    debug {
      signingConfig = signingConfigs.getByName("debugConfig")
      // A debug build carried the same applicationId as the release one while
      // being signed with another key: Android then refuses to replace one by
      // the other and says only "App not installed", with no reason given.
      // Under its own id, a debug build sits beside the real app instead of
      // blocking it.
      applicationIdSuffix = ".debug"
      versionNameSuffix = "-debug"
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
}

// Where Room writes the schema of each database version. The files belong in
// version control: they are what lets Room verify a migration instead of
// dropping the tables of a user who updates the app.
ksp {
  arg("room.schemaLocation", "$projectDir/schemas")
}

