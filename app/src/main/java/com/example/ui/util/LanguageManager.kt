    /** Switches language without a Context; used by the translation test. */
    internal fun setLanguageForTest(lang: String) {
        if (lang in translations.keys) _currentLang.value = lang
    }

    /** The three language codes, for the test that keeps them in step. */
    internal val languages: Set<String> get() = translations.keys

    /** The keys one language carries, for the test that keeps them in step. */
    internal fun keysOf(lang: String): Set<String> = translations[lang]?.keys.orEmpty()

    fun getString(key: String, vararg args: Pair<String, Any>): String {
        val lang = _currentLang.value
        var result = translations[lang]?.get(key) ?: translations["mg"]?.get(key) ?: key
        args.forEach { arg ->
            result = result.replace("{${arg.first}}", arg.second.toString())
        }
        return result
    }

    /**
     * The language picker. It lives in the settings only: the app bar of every
     * screen used to carry it, which cost space on the screens that need it most.
     */
    @Composable
    fun LanguageSelector(modifier: Modifier = Modifier) {
        val context = LocalContext.current
        val current = currentLang.value
        Row(
            modifier = modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.spacedBy(8.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            listOf(
                "mg" to getString("lang_mg"),
                "fr" to getString("lang_fr"),
                "en" to getString("lang_en")
            ).forEach { (code, label) ->
                val isSelected = current == code
                Surface(
                    onClick = { setLanguage(context, code) },
                    shape = RoundedCornerShape(12.dp),
                    color = if (isSelected) {
                        MaterialTheme.colorScheme.primaryContainer
                    } else {
                        MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.35f)
                    },
                    contentColor = if (isSelected) {
                        MaterialTheme.colorScheme.onPrimaryContainer
                    } else {
                        MaterialTheme.colorScheme.onSurfaceVariant
                    },
                    border = if (isSelected) {
                        BorderStroke(1.dp, MaterialTheme.colorScheme.primary)
                    } else {
                        null
                    },
                    modifier = Modifier.weight(1f)
                ) {
                    Text(
                        text = label,
                        fontSize = 13.sp,
                        fontWeight = if (isSelected) FontWeight.ExtraBold else FontWeight.Medium,
                        textAlign = TextAlign.Center,
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(vertical = 12.dp)
                    )
                }
            }
        }
    }
